"""Turn the JSON files in data/ into app/data.js, which the app loads.

Run: python3 scripts/build_data.py
Edit the files in data/, never app/data.js (it gets overwritten).
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(name):
    with open(os.path.join(ROOT, "data", name), encoding="utf-8") as f:
        return json.load(f)


def main():
    day1 = load("day1.json")
    teams = load("teams.json")
    fa = load("fa2027.json")
    out = {"day1": day1, "teams": teams["teams"], "teamsNote": teams["note"],
           "teamsSource": teams["source"], "fa": fa}
    js = ("// Generated by scripts/build_data.py from data/*.json. Do not edit by hand.\n"
          "window.SONICS_DATA = " + json.dumps(out, indent=1) + ";\n")
    with open(os.path.join(ROOT, "app", "data.js"), "w", encoding="utf-8") as f:
        f.write(js)
    print("Wrote app/data.js:", len(day1["roster"]), "players,", len(teams["teams"]), "opponents,",
          len(fa["players"]), "free agents")


if __name__ == "__main__":
    main()
